"""Explicit finite Cartesian grids. No physical source or coordinate inference."""
import itertools
import math
from .models import Port, ValueType, Axis

GRID_OUTPUT = "rows"
BATCH_AXIS = "batch_rows"
MAX_GRID_ROWS = 1000
BATCH_INPUT_FIELD_TYPES = ("number", "array")
BATCH_FIELD_TYPES = ("number", "array", "string")


def grid_interface(ports, axes):
    fields={}
    used=set()
    for target,address in axes.items():
        if not target.isidentifier() or target.startswith('_'):raise ValueError('非法网格字段')
        parts=address.split('.')
        if len(parts)!=2 or parts[0] not in ports:raise ValueError('网格轴必须明确为输入字典.字段')
        bag,key=parts
        p=ports[bag].fields.get(key)
        if p is None or p.type!='array' or p.value_type.dtype=='string' or len(p.value_type.shape)!=1:raise ValueError('网格轴必须为已声明的一维数值数组')
        if not p.required:raise ValueError('网格轴不能为可选字段')
        used.add(bag)
        fields[target]=p.model_copy(deep=True,update={'value_type':ValueType(dtype=p.value_type.dtype,shape=[BATCH_AXIS]),'axes':[Axis(name=BATCH_AXIS)]})
    if used!=set(ports):raise ValueError('网格不得包含未使用的输入字典')
    return ports,{GRID_OUTPUT:Port(type='flat_dict',fields=fields)}


def evaluate_grid(values,axes):
    columns=[]
    for address in axes.values():
        bag,key=address.split('.');column=values[bag][key]
        if not len(column):raise ValueError('网格轴不能为空')
        columns.append(column)
    count=math.prod(map(len,columns))
    if count>MAX_GRID_ROWS:raise ValueError('有限网格最多 1000 行')
    rows=list(itertools.product(*columns))
    return {GRID_OUTPUT:{name:[row[i] for row in rows] for i,name in enumerate(axes)}}


def row_port(columns):
    if columns.type!='flat_dict':raise ValueError('循环 rows 必须是数值列字典')
    fields={}
    for name,p in columns.fields.items():
        if p.type!='array' or not p.value_type or p.value_type.dtype=='string' or p.value_type.shape!=[BATCH_AXIS] or not p.required:
            raise ValueError('循环列必须共享显式 batch_rows 一维形状且必填')
        fields[name]=p.model_copy(deep=True,update={'type':'number','kind':'bare','value_type':ValueType(dtype=p.value_type.dtype),'axes':[]})
    return Port(type='flat_dict',fields=fields)


