class TransformerSelector():
    def __init__(self):
        # 磁芯参数：饱和磁通密度
        self.b_s = 0.39
        self.b_max = self.b_s * 0.6
        # 磁芯参数：电流密度=8A/mm^2
        self.j = 8.0
        # 磁芯参数：窗口利用系数
        self.k_u = 0.4
        # 磁芯参数：波形系数
        self.k_f = 4.0

    # ========== Part 1：变压器选型 ==========
    def select_transformer(self, current_dict, evalution=False):
        """
        Part1：变压器选型
        输入：工况 + 目标匝比
        输出：包含磁芯、绕组、几何尺寸的字典 transformer_params_dict
        （键名与原程序保持一致）
        """

        # --- 小工具1：算 AP ---
        def _calcu_ap(Vin, Vout, n, frequency, ip_rms):
            p_t = Vin * ip_rms + Vout * n * ip_rms
            ap = p_t * 1e4 / (self.k_f * self.k_u * self.b_max * (self.j * 100) * frequency)
            # 返回 m^4
            return ap * 1.2 * 1e-8

        # --- 小工具2：给定磁芯，算 Ns ---
        def _calcu_Ns(Vout, frequency, Ae):
            Ds = 0.5  # 副边占空比
            N_s = int(Vout * Ds / (frequency * Ae * 2 * self.b_max)) + 1
            return N_s

        # --- 小工具3：原/副边利兹线选型 ---
        def _select_wire(n_real, ip_rms):
            single_area = (0.1 / 2) * (0.1 / 2) * np.pi  # 0.1mm 利兹线单股截面积 mm^2
            num_p = ip_rms / self.j / single_area
            num_s = n_real * ip_rms / self.j / single_area

            wire_p = None
            wire_s = None

            for wire, params in wire_D001.items():
                if num_p <= params['num']:
                    wire_p = wire
                    break

            for wire, params in wire_D001.items():
                if num_s <= params['num']:
                    wire_s = wire
                    break

            return wire_p, wire_s

        # --- 小工具4：绕组长度 & 宽度 ---
        def _calcu_wire_length(core_name, Np, Ns, wire_p, wire_s):
            core = ee_cores[core_name]
            Tr_C = core['C']
            Tr_D = core['D']
            Tr_F = core['F']

            Np_per_layer = int(2 * Tr_F / wire_D001[wire_p]['D'])
            Ns_per_layer = int(2 * Tr_F / wire_D001[wire_s]['D'])

            layer_p = int(Np / Np_per_layer) + 1
            layer_s = int(Ns / Ns_per_layer) + 1

            # 绕组绕法：原边在内，副边在外
            wire_length_p = Np * (layer_p / 2 * wire_D001[wire_p]['D'] * 8 + 2 * Tr_C + 2 * Tr_D)
            wire_length_s = Ns * (
                layer_p * wire_D001[wire_p]['D'] * 8
                + 2 * Tr_C + 2 * Tr_D
                + layer_s / 2 * wire_D001[wire_s]['D'] * 8
            )

            wire_width = layer_p * wire_D001[wire_p]['D'] + layer_s * wire_D001[wire_s]['D']
            return wire_length_p, wire_length_s, wire_width

        # --- 小工具5：计算体积（mm^3） ---
        def _calcu_volume(core_name, wire_width):
            core = ee_cores[core_name]
            A = core['A']
            B = core['B']
            C = core['C']
            return A * 2 * B * (C + 2 * wire_width)

        # ================= 实际选型流程 =================
        Vin = current_dict['v_rms_p']
        Vout = current_dict['v_rms_s']
        n = current_dict['n']
        frequency = current_dict['fs_min']
        ip_rms = current_dict['i_rms_p_max']
        Vout_max = current_dict['v_rms_s_max']

        transformer_params_dict = {}

        # 1) 计算目标 AP
        ap_target = _calcu_ap(Vin, Vout, n, frequency, ip_rms)
        if evalution:
            print(f"目标 AP: {ap_target}")
        transformer_params_dict['Ap_target'] = ap_target

        # 2) 遍历磁芯库
        for core_name, params in ee_cores.items():
            if ap_target > params['Ap']:
                # 该磁芯 AP 不足
                continue

            Ae = params['Ae']   # m^2
            Ve = params['Ve']   # m^3

            # 3) 计算 Ns, Np
            Ns = _calcu_Ns(Vout_max, frequency, Ae)
            Np = int(Ns * n) + 1
            n_real = Np / Ns

            if evalution:
                print(f"尝试磁芯 {core_name}: Np={Np}, Ns={Ns}, n_real={n_real:.3f}")

            # 4) 选择利兹线
            wire_p, wire_s = _select_wire(n_real, ip_rms)
            if wire_p is None or wire_s is None:
                # 利兹线根本选不出来，直接失败
                return None

            # 5) 窗口面积检查
            need_area = (wire_D001[wire_p]['D'] ** 2) * Np + (wire_D001[wire_s]['D'] ** 2) * Ns
            aw_mm2 = params['Aw'] * 1e6
            if need_area > aw_mm2:
                if evalution:
                    print(f"{core_name} 窗口不足: need={need_area:.1f} > Aw={aw_mm2:.1f}")
                continue

            # 6) 计算绕组长度 & 宽度
            wire_length_p, wire_length_s, wire_width = _calcu_wire_length(
                core_name, Np, Ns, wire_p, wire_s
            )

            # 7) 计算体积
            volume = _calcu_volume(core_name, wire_width)

            # === 打包输出字典（与原键一致 + 额外几何信息）===
            transformer_params_dict.update({
                # 原有关键几何参数
                'core_T': core_name,
                'Ns': Ns,
                'Np': Np,
                'n': n_real,
                'wire_p': wire_p,
                'wire_s': wire_s,
                'wire_length_p': wire_length_p,
                'wire_length_s': wire_length_s,
                'wire_width': wire_width,

                # 便于后续损耗和磁密计算的几何量
                'Ae_T': Ae,                             #磁芯截面积
                'Ve_T': Ve,                              #磁芯体积
                'V_T': volume,                           # 整体体积 mm^3
                'wire_area_p': wire_D001[wire_p]['S'],      # mm^2
                'wire_area_s': wire_D001[wire_s]['S'],      # mm^2
                'Ap_core': params['Ap'],                    # 该磁芯自身的 Ap
            })

            if evalution:
                print(f"选型成功: core={core_name}, volume={volume:.1f} mm^3")
            return transformer_params_dict

        # 遍历完都失败
        if evalution:
            print("未找到满足 AP 与窗口条件的磁芯")
        return None

